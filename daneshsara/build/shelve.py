def norm(t):
    t = re.sub(r'\.(pdf|epub|djvu|docx?|txt|apk|zip)$', '', t, flags=re.I)
    t = t.replace('‌', ' ').replace('_', ' ')
    t = re.sub(r'[\(\)\[\]]', ' ', t)
    t = re.sub(r'\s*\d+\s*$', '', t)
    return re.sub(r'\s+', ' ', t).strip()

