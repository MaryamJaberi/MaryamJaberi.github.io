"""Site-wide «نقشه» panel + hover previews.
Writes core/preview.json (title + one-line summary for every page and every concept) and core/nav.js (one small script,
loaded on every page by crumbs.py).  python3 build/nav.py   — run after the pages exist, before crumbs.py."""
import os, json, glob, re, html
R = os.path.abspath(os.path.dirname(os.path.abspath(__file__)) + '/..')
os.chdir(R)
cut = lambda t, n=170: t if len(t) <= n else t[:n - 2].rsplit(' ', 1)[0] + '…'
txt = lambda h: re.sub(r'\s+', ' ', html.unescape(re.sub('<[^>]*>', '', h))).strip()
WN = {'psy': 'روان‌شناسی', 'soc': 'جامعه', 'phil': 'فلسفه', 'tabar': 'تبار و ژنتیک', 'tarikh': 'تاریخ', 'iran': 'ایران'}
P = {}
for p in sorted(glob.glob('**/*.html', recursive=True)):
    if p.startswith('build/'): continue
    s = open(p, encoding='utf-8', errors='ignore').read()
    if 'http-equiv="refresh"' in s: continue
    t = re.search(r'<title[^>]*>(.*?)</title>', s, re.S); d = re.search(r'<meta name="description" content="([^"]*)"', s)
    t = txt(t.group(1)).split(' | ')[0] if t else p
    P[p.replace(os.sep, '/')] = [t, cut(html.unescape(d.group(1))) if d else '']
C = {}
for p in glob.glob('data/*/concepts/*.json'):
    c = json.load(open(p, encoding='utf-8'))
    if not isinstance(c, dict) or 'id' not in c: continue
    w = c['id'].split(':')[0]
    C[c['id']] = [c['title']['fa'], cut((c.get('summary') or {}).get('fa') or ''), WN.get(w, w)]
for p in glob.glob('iran/*.json'):
    n = json.load(open(p, encoding='utf-8'))
    C[n['id']] = [n['question']['fa'], cut((n.get('finding') or {}).get('fa') or ''), 'ایران']
json.dump({'p': P, 'c': C}, open('core/preview.json', 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))

